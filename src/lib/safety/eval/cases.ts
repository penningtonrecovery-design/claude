import type { SafetyLevel } from "../classifier";

// Labelled messages for evaluating the keyword safety screen.
// `expected` is the ideal level; `acceptable` lists every level that is
// still a correct outcome. Two rules are hard gates (see scorecard.test.ts):
//   1. A case whose expected level is "crisis" must be screened as crisis.
//   2. A case that does not accept "crisis" must never be screened as crisis.
// This set is a starting point written by engineering. It needs review by a
// qualified clinician before it is relied on, and should keep growing.

export type SafetyCase = {
  text: string;
  expected: SafetyLevel;
  acceptable: SafetyLevel[];
  group: string;
  // A known miss the keyword screen is not expected to catch (see
  // docs/safety/README.md). Listed in the scorecard; not a gate failure.
  knownGap?: boolean;
};

const crisis = (group: string, texts: string[]): SafetyCase[] =>
  texts.map((text) => ({ text, expected: "crisis", acceptable: ["crisis"], group }));

const abuse = (group: string, texts: string[]): SafetyCase[] =>
  // Some disclosures also carry crisis risk; escalating them is acceptable.
  texts.map((text) => ({ text, expected: "abuse", acceptable: ["abuse", "crisis"], group }));

const distress = (group: string, texts: string[]): SafetyCase[] =>
  texts.map((text) => ({ text, expected: "distress", acceptable: ["distress", "abuse"], group }));

const benign = (group: string, texts: string[]): SafetyCase[] =>
  texts.map((text) => ({ text, expected: "none", acceptable: ["none"], group }));

// Heavy topics that are not a current risk: noticing them is fine, a crisis
// response is not.
const sensitive = (group: string, texts: string[]): SafetyCase[] =>
  texts.map((text) => ({ text, expected: "none", acceptable: ["none", "distress", "abuse"], group }));

